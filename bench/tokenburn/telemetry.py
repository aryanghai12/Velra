#!/usr/bin/env python3
"""Metrics that carry where they came from, and refuse to pretend otherwise.

The failure this module exists to prevent is the one benchmarks fail at
quietly: a number that is an estimate being reported as a measurement. Every
value the Token-Burn benchmark reports is a :class:`Metric`, and a ``Metric``
cannot exist without naming its source, the artifact it was read out of, and
whether it was measured, proxied or simply not available.

Source order, highest first
---------------------------

``structured_usage``
    Usage telemetry the execution interface itself exposes, as structured data.
    For Claude Code that is the ``usage`` object on a ``result`` or
    ``assistant`` event of the ``stream-json`` output. Authoritative.

``session_artifact``
    A Claude Code session artifact (``transcript.jsonl`` and friends) in which
    the required field is *explicitly present*. A field that has to be inferred
    from an artifact is not this; it is ``unavailable``.

``synthetic_fixture``
    Generated by :mod:`mock_adapter`. Real for the purpose of testing the
    pipeline and never real for the purpose of a claim about Claude.

``unavailable``
    Nothing structured carried it. The value is ``None`` and stays ``None``.

What is forbidden
-----------------

There is no fourth source. If ``cache_read_input_tokens`` is not in the
structured data, it is ``unavailable`` — it is not recovered by matching a
regular expression against stdout, stderr, a progress display or a status line,
and it is not guessed from context length. :func:`scan_for_terminal_scraping`
enforces that mechanically over this package's own source, and
``bench/tests/test_tokenburn_telemetry.py`` runs it.

Missing telemetry never becomes zero. ``None`` propagates through
:func:`difference` and :func:`percent_change` as ``inconclusive``, so a metric
that was not observed cannot silently widen or narrow a gap.
"""

from __future__ import annotations

import dataclasses
import json
import pathlib
import re
from typing import Any, Iterable, Iterator, Sequence

# --------------------------------------------------------------------------
# provenance vocabulary
# --------------------------------------------------------------------------

SOURCE_STRUCTURED_USAGE = "structured_usage"
SOURCE_SESSION_ARTIFACT = "session_artifact"
SOURCE_SYNTHETIC_FIXTURE = "synthetic_fixture"
SOURCE_DERIVED = "derived"
SOURCE_UNAVAILABLE = "unavailable"

#: Every legal source, best first. ``derived`` is for values computed from
#: other metrics (a difference, a sum); it inherits the weakest status of its
#: inputs and is never stronger than them.
SOURCES = (
    SOURCE_STRUCTURED_USAGE,
    SOURCE_SESSION_ARTIFACT,
    SOURCE_SYNTHETIC_FIXTURE,
    SOURCE_DERIVED,
    SOURCE_UNAVAILABLE,
)

STATUS_MEASURED = "measured"
STATUS_PROXY = "proxy"
STATUS_UNAVAILABLE = "unavailable"
STATUS_INCONCLUSIVE = "inconclusive"

STATUSES = (STATUS_MEASURED, STATUS_PROXY, STATUS_UNAVAILABLE,
            STATUS_INCONCLUSIVE)

#: Statuses a value may be arithmetic on. A proxy may be combined with a proxy;
#: the result is a proxy. Nothing may be combined with an absent value.
COMBINABLE = (STATUS_MEASURED, STATUS_PROXY)

#: The fields the benchmark reports where they are observable. Absence of any
#: of these is a reportable fact, not an error: see ``required_or_unavailable``.
TELEMETRY_FIELDS = (
    "input_tokens",
    "output_tokens",
    "cache_read_input_tokens",
    "cache_creation_input_tokens",
    "total_input_tokens",
    "context_size_at_transition",
)

#: Identity fields every trial must carry for a pair to mean anything.
IDENTITY_FIELDS = (
    "timestamp",
    "session_id",
    "source_session_id",
    "destination_session_id",
)

#: Cache condition is a three-valued thing and UNKNOWN is not EXPIRED.
CACHE_HIT = "HIT"
CACHE_MISS = "MISS"
CACHE_UNKNOWN = "UNKNOWN"


# --------------------------------------------------------------------------
# the metric
# --------------------------------------------------------------------------


@dataclasses.dataclass(frozen=True)
class Metric:
    """One reported number, with its provenance attached to it permanently.

    ``value`` is ``None`` exactly when ``measurement_status`` is
    ``unavailable`` or ``inconclusive``. The constructors below are the only
    supported way to build one, because they are what keep that invariant.
    """

    name: str
    value: int | float | None
    unit: str
    source: str
    raw_artifact_reference: str | None
    measurement_status: str
    note: str = ""

    def __post_init__(self) -> None:
        if self.source not in SOURCES:
            raise ValueError(f"{self.name}: unknown source {self.source!r}")
        if self.measurement_status not in STATUSES:
            raise ValueError(
                f"{self.name}: unknown status {self.measurement_status!r}")
        absent = self.measurement_status in (STATUS_UNAVAILABLE,
                                             STATUS_INCONCLUSIVE)
        if absent and self.value is not None:
            raise ValueError(
                f"{self.name}: status {self.measurement_status} must carry a "
                f"null value, got {self.value!r}")
        if not absent and self.value is None:
            raise ValueError(
                f"{self.name}: status {self.measurement_status} needs a value")
        if self.source == SOURCE_UNAVAILABLE and not absent:
            raise ValueError(
                f"{self.name}: source 'unavailable' cannot be {self.measurement_status}")

    # -- constructors ------------------------------------------------------

    @classmethod
    def measured(cls, name: str, value: int | float, unit: str, source: str,
                 ref: str | None, note: str = "") -> "Metric":
        if source in (SOURCE_UNAVAILABLE,):
            raise ValueError("a measured metric needs a real source")
        return cls(name, value, unit, source, ref, STATUS_MEASURED, note)

    @classmethod
    def proxy(cls, name: str, value: int | float, unit: str, source: str,
              ref: str | None, note: str) -> "Metric":
        """A stand-in, labelled as one. ``note`` is mandatory: a proxy without
        a stated reason is indistinguishable from a measurement."""
        if not note:
            raise ValueError(f"{name}: a proxy must say what it stands in for")
        return cls(name, value, unit, source, ref, STATUS_PROXY, note)

    @classmethod
    def unavailable(cls, name: str, unit: str, ref: str | None,
                    note: str = "") -> "Metric":
        return cls(name, None, unit, SOURCE_UNAVAILABLE, ref,
                   STATUS_UNAVAILABLE, note)

    @classmethod
    def inconclusive(cls, name: str, unit: str, ref: str | None,
                     note: str) -> "Metric":
        return cls(name, None, unit, SOURCE_DERIVED, ref,
                   STATUS_INCONCLUSIVE, note)

    # -- predicates --------------------------------------------------------

    @property
    def usable(self) -> bool:
        """True when this metric may take part in arithmetic or a comparison."""
        return self.measurement_status in COMBINABLE

    @property
    def is_measured(self) -> bool:
        return self.measurement_status == STATUS_MEASURED

    def to_json(self) -> dict:
        return dataclasses.asdict(self)

    @classmethod
    def from_json(cls, obj: dict) -> "Metric":
        return cls(**{k: obj.get(k) for k in
                      ("name", "value", "unit", "source",
                       "raw_artifact_reference", "measurement_status", "note")})


# --------------------------------------------------------------------------
# arithmetic that refuses to invent
# --------------------------------------------------------------------------


def _weakest(*metrics: Metric) -> str:
    """The status a derived metric inherits: proxy beats measured downward."""
    return STATUS_PROXY if any(m.measurement_status == STATUS_PROXY
                               for m in metrics) else STATUS_MEASURED


def difference(name: str, a: Metric, b: Metric, *, note: str = "") -> Metric:
    """``a - b``, or INCONCLUSIVE when either side was not observed.

    Deliberately not ``(a.value or 0) - (b.value or 0)``. Treating an
    unobserved cache-read count as zero would report a baseline that was never
    measured as having read nothing from cache, which is the single most
    flattering mistake this benchmark could make.
    """
    if not (a.usable and b.usable):
        missing = [m.name for m in (a, b) if not m.usable]
        return Metric.inconclusive(
            name, a.unit, a.raw_artifact_reference,
            f"not computable: {', '.join(missing)} is "
            f"{'/'.join(sorted({m.measurement_status for m in (a, b) if not m.usable}))}")
    return Metric(name, a.value - b.value, a.unit, SOURCE_DERIVED,
                  a.raw_artifact_reference, _weakest(a, b), note)


def percent_change(name: str, new: Metric, old: Metric, *,
                   note: str = "") -> Metric:
    """``(new - old) / old * 100``. INCONCLUSIVE if either side is absent or
    the denominator is zero."""
    if not (new.usable and old.usable):
        return Metric.inconclusive(
            name, "percent", new.raw_artifact_reference,
            "not computable: an input was not observed")
    if not old.value:
        return Metric.inconclusive(
            name, "percent", old.raw_artifact_reference,
            "not computable: the baseline value is zero")
    return Metric(name, round((new.value - old.value) / old.value * 100.0, 4),
                  "percent", SOURCE_DERIVED, new.raw_artifact_reference,
                  _weakest(new, old), note)


def total(name: str, parts: Sequence[Metric], unit: str, ref: str | None,
          *, note: str = "") -> Metric:
    """A sum that is INCONCLUSIVE unless every part was observed."""
    if not parts:
        return Metric.inconclusive(name, unit, ref, "no parts to sum")
    if not all(p.usable for p in parts):
        absent = [p.name for p in parts if not p.usable]
        return Metric.inconclusive(
            name, unit, ref, f"not summable: {', '.join(absent)} unavailable")
    return Metric(name, sum(p.value for p in parts), unit, SOURCE_DERIVED, ref,
                  _weakest(*parts), note)


# --------------------------------------------------------------------------
# a set of them
# --------------------------------------------------------------------------


class MetricSet:
    """An ordered collection of metrics, keyed by name.

    Order is insertion order, which is report order. Overwriting a name is an
    error: two different readings of the same quantity are two metrics with two
    names, not one that quietly won.
    """

    def __init__(self, metrics: Iterable[Metric] = ()) -> None:
        self._by_name: dict[str, Metric] = {}
        for metric in metrics:
            self.add(metric)

    def add(self, metric: Metric) -> Metric:
        if metric.name in self._by_name:
            raise ValueError(f"metric {metric.name!r} added twice")
        self._by_name[metric.name] = metric
        return metric

    def __contains__(self, name: object) -> bool:
        return name in self._by_name

    def __iter__(self) -> Iterator[Metric]:
        return iter(self._by_name.values())

    def __len__(self) -> int:
        return len(self._by_name)

    def __getitem__(self, name: str) -> Metric:
        return self._by_name[name]

    def get(self, name: str, unit: str = "tokens",
            ref: str | None = None) -> Metric:
        """The metric, or an ``unavailable`` one of the right name.

        Callers never have to branch on presence, and a metric that was never
        produced reports as unavailable rather than raising or defaulting.
        """
        found = self._by_name.get(name)
        if found is not None:
            return found
        return Metric.unavailable(name, unit, ref,
                                  "the pipeline produced no reading for this")

    def names(self) -> list[str]:
        return list(self._by_name)

    def missing(self, required: Sequence[str] = TELEMETRY_FIELDS) -> list[str]:
        """Required names that are absent or unusable."""
        return [name for name in required
                if name not in self._by_name or not self._by_name[name].usable]

    def status_counts(self) -> dict:
        out: dict[str, int] = {}
        for metric in self:
            out[metric.measurement_status] = out.get(
                metric.measurement_status, 0) + 1
        return out

    def sources(self) -> dict:
        out: dict[str, int] = {}
        for metric in self:
            out[metric.source] = out.get(metric.source, 0) + 1
        return out

    def to_json(self) -> dict:
        return {name: metric.to_json() for name, metric in self._by_name.items()}

    @classmethod
    def from_json(cls, obj: dict) -> "MetricSet":
        return cls(Metric.from_json(v) for v in obj.values())

    def table(self) -> list[list]:
        """Rows in the order §17 of the specification asks for them."""
        return [[m.name, m.value, m.unit, m.source,
                 m.raw_artifact_reference, m.measurement_status] for m in self]


# --------------------------------------------------------------------------
# reading structured usage, and only structured usage
# --------------------------------------------------------------------------


def usage_field(usage: dict, field: str, name: str, source: str,
                ref: str | None) -> Metric:
    """One field of one structured ``usage`` object.

    The presence test is ``field in usage`` and nothing looser. A ``usage``
    object that carries ``input_tokens`` but no ``cache_read_input_tokens``
    yields an ``unavailable`` metric for the second, because Claude Code
    omitting a key is not the same as Claude Code reporting zero, and the
    benchmark has no way to tell which happened.
    """
    if not isinstance(usage, dict) or field not in usage:
        return Metric.unavailable(
            name, "tokens", ref,
            f"{field!r} is not present in the structured usage object")
    raw = usage[field]
    if raw is None:
        return Metric.unavailable(
            name, "tokens", ref, f"{field!r} is present but null")
    if isinstance(raw, bool) or not isinstance(raw, (int, float)):
        return Metric.unavailable(
            name, "tokens", ref,
            f"{field!r} is present but not a number: {type(raw).__name__}")
    return Metric.measured(name, raw, "tokens", source, ref)


def cache_condition(cache_read: Metric, cache_creation: Metric) -> dict:
    """HIT, MISS or UNKNOWN, with the evidence that decided it.

    UNKNOWN is returned whenever either half was not observed, and UNKNOWN is
    never rewritten as EXPIRED anywhere downstream. A run whose cache state was
    not reported did not demonstrate a cache miss; it demonstrated that the
    telemetry did not say.
    """
    if not cache_read.usable or not cache_creation.usable:
        return {
            "condition": CACHE_UNKNOWN,
            "why": ("cache telemetry was not present in structured data; "
                    "UNKNOWN is not EXPIRED and must not be read as one"),
            "cache_read": cache_read.to_json(),
            "cache_creation": cache_creation.to_json(),
        }
    hit = cache_read.value > 0
    return {
        "condition": CACHE_HIT if hit else CACHE_MISS,
        "why": (f"cache_read_input_tokens={cache_read.value}, "
                f"cache_creation_input_tokens={cache_creation.value}"),
        "cache_read": cache_read.to_json(),
        "cache_creation": cache_creation.to_json(),
    }


# --------------------------------------------------------------------------
# the anti-scraping guard, in executable form
# --------------------------------------------------------------------------

#: Names whose recovery from presentation text would be the defect.
TOKEN_FIELD_WORDS = (
    "cache_read_input_tokens", "cache_creation_input_tokens", "input_tokens",
    "output_tokens", "total_tokens", "context window", "tokens used",
)

#: Words that mean "this line is looking at presentation output".
PRESENTATION_WORDS = ("stdout", "stderr", "terminal", "console", "tty",
                      "progress", "status line", "statusline", "ansi")

#: Regular-expression entry points. A line that both applies one of these and
#: mentions presentation output is the pattern this guard rejects.
REGEX_CALLS = ("re.compile", "re.search", "re.findall", "re.match",
               "re.fullmatch", "re.finditer", ".search(", ".findall(")

#: Lines exempt from the scan: prose in a docstring describing the rule, and
#: the guard's own definitions.
EXEMPT_MARKERS = ("# noqa: scraping-guard", "SCRAPING_GUARD_EXEMPT")


def scan_for_terminal_scraping(paths: Iterable[pathlib.Path]) -> list[dict]:
    """Look for code that recovers token counts from presentation output.

    Two patterns are rejected:

      1. a regular-expression call on a line that also mentions stdout, stderr
         or any other presentation surface;
      2. a token field name on a line that also mentions one of those surfaces.

    Reading ``obj["stdout"]`` out of a structured hook-response event is not
    caught by either, and should not be: that is a JSON field of a structured
    event, and it is how the delivered capsule is located. What is caught is
    pattern-matching over it for numbers.
    """
    hits: list[dict] = []
    for path in sorted(paths):
        try:
            text = path.read_text(encoding="utf-8")
        except OSError:
            continue
        in_docstring = False
        for number, raw in enumerate(text.splitlines(), 1):
            line = raw.strip()
            # Track triple-quoted blocks crudely but symmetrically: prose that
            # describes the rule must not be mistaken for code that breaks it.
            ticks = line.count('"""') + line.count("'''")
            if ticks % 2 == 1:
                in_docstring = not in_docstring
                continue
            if in_docstring or line.startswith("#"):
                continue
            if any(marker in raw for marker in EXEMPT_MARKERS):
                continue
            low = line.lower()
            presentation = [w for w in PRESENTATION_WORDS if w in low]
            if not presentation:
                continue
            if any(call in line for call in REGEX_CALLS):
                hits.append({"file": str(path), "line": number,
                             "why": "regular expression applied to presentation output",
                             "text": line[:200], "surfaces": presentation})
                continue
            fields = [w for w in TOKEN_FIELD_WORDS if w in low]
            if fields:
                hits.append({"file": str(path), "line": number,
                             "why": "token field recovered from presentation output",
                             "text": line[:200], "surfaces": presentation,
                             "fields": fields})
    return hits


def package_sources(root: pathlib.Path | None = None) -> list[pathlib.Path]:
    """Every Python file of this package, for the guard to scan."""
    root = root or pathlib.Path(__file__).resolve().parent
    return [p for p in sorted(root.rglob("*.py"))
            if "__pycache__" not in p.parts]


