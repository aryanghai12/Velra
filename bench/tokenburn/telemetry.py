def read_jsonl(path: pathlib.Path) -> tuple[list[dict], list[dict]]:
    """Every decodable object, and a record of every line that was not.

    Malformed lines are counted and carried, never raised and never silently
    dropped: ``parse.py`` reports the count, the analysis survives it, and a
    capture that is mostly garbage is visible as such instead of looking empty.
    """
    good: list[dict] = []
    bad: list[dict] = []
    if not path.exists():
        return good, bad
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        for number, raw in enumerate(fh, 1):
            line = raw.strip()
            if not line:
                continue
            try:
                obj = json.loads(line)
            except json.JSONDecodeError as exc:
                bad.append({"line": number, "error": str(exc),
                            "text": line[:160]})
                continue
            if isinstance(obj, dict):
                good.append(obj)
            else:
                bad.append({"line": number, "error": "not a JSON object",
                            "text": line[:160]})
    return good, bad


def read_json(path: pathlib.Path) -> Any:
    """A JSON file, or ``None`` when it is absent or unreadable.

    Unreadable is not fatal anywhere in this pipeline. A trial missing an
    artifact produces unavailable metrics and an incomplete causal chain, which
    is the honest result; crashing would lose the other trials too.
    """
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError, UnicodeDecodeError):
        return None


_WS = re.compile(r"\s+")


def collapse(text: str | None) -> str:
    return _WS.sub(" ", text or "").strip()
